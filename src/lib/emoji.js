const RULES = [
  [/омлет|яичниц/i, '🍳'],
  [/суп|борщ|бульон/i, '🍲'],
  [/салат|шуб/i, '🥗'],
  [/каша|овсян|пшён|манн/i, '🥣'],
  [/бутерброд/i, '🥪'],
  [/плов/i, '🍚'],
  [/рис/i, '🍚'],
  [/макарон|вермишел/i, '🍝'],
  [/сырник|оладь/i, '🥞'],
  [/котлет/i, '🍖'],
  [/рыб|минтай|горбуш|сельд/i, '🐟'],
  [/картош|картофел/i, '🥔'],
  [/капуст|голубц/i, '🥬'],
  [/творог/i, '🧀'],
  [/перец фарширован/i, '🫑'],
  [/кабачк/i, '🥒'],
  [/гриб/i, '🍄'],
]

export function getRecipeEmoji(recipe) {
  for (const [pattern, emoji] of RULES) {
    if (pattern.test(recipe.name)) return emoji
  }
  return '🍽️'
}
