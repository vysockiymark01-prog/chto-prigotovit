// Шуточные комментарии к результату семейного голосования.
// {dish} подставляется на месте названия выбранного блюда.

const GENERIC_JOKES = [
  'Судьба ужина решена: {dish}. Обжалованию не подлежит.',
  'Голосование честное, рандом — тоже. Сегодня {dish}!',
  'Демократия сработала — готовим {dish}.',
  'Барабанная дробь… и это {dish}! Никто не ожидал (кроме автора идеи).',
  'Колесо фортуны выбрало {dish}. Кухня, мы идём.',
  'Итог голосования: {dish}. Возражения не принимаются, кроме как от голодных.',
  '{dish} — и точка. Ставьте таймер на плите.',
  'Семейный совет постановил: сегодня {dish}.',
]

const REPEAT_JOKES = [
  'Опять {dish}? Ну ладно, видимо, это судьба.',
  '{dish} снова в топе. У кого-то один любимый вариант, признавайтесь.',
  'Рандом второй раз подряд выбирает {dish} — подозрительно, но окей.',
  '{dish}… Ну хотя бы рецепт уже отточен до автоматизма.',
]

function pickRandom(list) {
  return list[Math.floor(Math.random() * list.length)]
}

export function pickJoke(dishName, isRepeat) {
  const template = isRepeat && Math.random() < 0.7 ? pickRandom(REPEAT_JOKES) : pickRandom(GENERIC_JOKES)
  return template.replace('{dish}', dishName)
}
